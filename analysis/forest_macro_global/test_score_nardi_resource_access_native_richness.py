"""Known-positive/negative resource versus access Native beetle effects and source stop."""
import importlib.util,math
from pathlib import Path
import pytest

SRC=Path(__file__).with_name("score_nardi_resource_access_native_richness.py")
spec=importlib.util.spec_from_file_location("nardi_resource_access",SRC)
m=importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)


def known_truth(kind):
    rows=[]
    for i in range(13):
        for j in range(15 if i==0 else 16):
            cover=20+((j*3)%7)*10
            access=15+j*4+(i%3)
            y=12+0.07*cover+ (0.15 if kind=="positive" else -0.15 if kind=="negative" else 0)*access+i*2
            rows.append({"site":f"secret_site_{i}","cover":cover,"access":access,"native":y})
    assert len(rows)==207
    return rows

def test_fwl_removes_site_and_cover_composition_before_unique_access():
    q=m.fwl(known_truth("positive"))
    assert abs(q["beta_access_per_1_percentage_point"]-0.15)<1e-10
    assert abs(q["beta_cover_per_1_percentage_point"]-0.07)<1e-10
    x=m.inference(known_truth("positive"),perm=199,boots=300)
    assert x["conditional_access_coefficient_native_detected_labels_per_10pct_unblocked_angle"]>1.49
    assert x["predeclared_access_positive_support"]
    assert x["within_landscape_reduced_model_residual_permutation_two_sided_p"]<=.05
    assert x["access_coefficient_13_landscape_cluster_bootstrap_95CI_per10pct"][0]>1.49
    assert x["leave_one_landscape_out_same_sign_as_full"]==13

def test_opposite_negative_and_true_zero_not_fished_into_support():
    n=m.inference(known_truth("negative"),perm=199,boots=300)
    assert n["conditional_access_coefficient_native_detected_labels_per_10pct_unblocked_angle"]<0
    assert not n["predeclared_access_positive_support"]
    zero=m.inference(known_truth("zero"),perm=99,boots=150)
    assert abs(zero["conditional_access_coefficient_native_detected_labels_per_10pct_unblocked_angle"])<1e-10
    assert not zero["predeclared_access_positive_support"]

def test_synthetic_exact_original_207_cells_3215_incidence_plus_301_taxa():
    original=Path(__file__).with_name("test_score_eight_country_beetle_exotic_urbanization.py")
    fixture_spec=importlib.util.spec_from_file_location("nardi_original_source_shape_fixture",original)
    mod=importlib.util.module_from_spec(fixture_spec)
    fixture_spec.loader.exec_module(mod)
    wide,long,site,env=mod.source_fixture("positive")
    # Trap-scale source independent tree cover and barriers; a known Native
    # response is generated by the existing original-shape synthetic fixture.
    for r in env[0]:
        j=int(r["CELL_ID"].split("_")[-1])
        r["composition"]=str(20+((j*3)%7)*10)
        r["configuration"]=str(100-j*5)
        r["urbanization_index"]=str(math.sqrt((100-float(r["composition"]))**2
                                               +(100-float(r["configuration"]))**2)/math.sqrt(2))
    # Synthetic shape has 3215 incidences but a different Native fraction
    # than the actual original 2915 Native incidences. This must fail closed,
    # rather than silently be treated as verified source observations.
    with pytest.raises(ValueError,match="original_native_incidence_2915_not_reproduced"):
        m.analyze(wide,long,site,env,perm=99,boots=150)

def test_collinear_access_and_tree_amount_cannot_generate_a_unique_effect():
    rows=known_truth("positive")
    for r in rows:r["access"]=r["cover"]*2
    with pytest.raises(ValueError,match="configuration_not_separable"):
        m.fwl(rows)
